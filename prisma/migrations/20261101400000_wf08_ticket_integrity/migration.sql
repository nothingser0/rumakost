CREATE FUNCTION sync_ticket_attachment_retention() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    PERFORM set_config('rumakost.ticket_retention_update', 'on', TRUE);
    IF NEW.status IN ('RESOLVED', 'CANCELLED') THEN
      UPDATE ticket_attachments
      SET delete_after = NEW.closed_at + INTERVAL '365 days'
      WHERE ticket_id = NEW.id AND upload_status NOT IN ('DELETED', 'FAILED');
    ELSIF OLD.status IN ('RESOLVED', 'CANCELLED') AND NEW.status NOT IN ('RESOLVED', 'CANCELLED') THEN
      UPDATE ticket_attachments
      SET delete_after = NULL
      WHERE ticket_id = NEW.id AND upload_status NOT IN ('DELETED', 'FAILED');
    END IF;
    PERFORM set_config('rumakost.ticket_retention_update', 'off', TRUE);
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER tickets_sync_attachment_retention
AFTER UPDATE OF status ON tickets
FOR EACH ROW EXECUTE FUNCTION sync_ticket_attachment_retention();

CREATE FUNCTION require_ticket_initial_attachment() RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  selected_ticket_id UUID;
BEGIN
  IF TG_TABLE_NAME = 'tickets' THEN
    selected_ticket_id := NEW.id;
  ELSE
    selected_ticket_id := NEW.ticket_id;
  END IF;

  IF EXISTS (SELECT 1 FROM tickets WHERE id = selected_ticket_id)
    AND NOT EXISTS (SELECT 1 FROM ticket_attachments WHERE ticket_id = selected_ticket_id) THEN
    RAISE EXCEPTION 'TICKET_MEDIA_REQUIRED: at least one attachment record is required';
  END IF;

  RETURN NULL;
END;
$$;

