CREATE FUNCTION record_ticket_status_change() RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO ticket_status_events
      (id, ticket_id, from_status, to_status, actor_id, reason, resolution_summary)
    VALUES
      (gen_random_uuid(), NEW.id, OLD.status, NEW.status, NEW.status_changed_by_id,
       CASE WHEN NEW.status = 'CANCELLED' THEN NEW.cancellation_reason ELSE NULL END,
       CASE WHEN NEW.status = 'RESOLVED' THEN NEW.resolution_summary ELSE NULL END);
  END IF;
  RETURN NEW;
END;
$$;

