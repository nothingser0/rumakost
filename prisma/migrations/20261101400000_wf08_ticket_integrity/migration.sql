DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM tickets
    WHERE btrim(title) = '' OR btrim(description) = ''
  ) THEN
    RAISE EXCEPTION 'TICKET_TEXT_BACKFILL_REQUIRED: existing ticket title or description is blank';
  END IF;

  IF EXISTS (SELECT 1 FROM tickets) THEN
    RAISE EXCEPTION 'TICKET_CATEGORY_BACKFILL_REQUIRED: map existing tickets before adding required category';
  END IF;

  IF EXISTS (SELECT 1 FROM ticket_comments WHERE btrim(body) = '') THEN
    RAISE EXCEPTION 'TICKET_COMMENT_BACKFILL_REQUIRED: existing comments contain blank bodies';
  END IF;

  IF EXISTS (
    SELECT 1 FROM ticket_attachments
    WHERE mime_type NOT IN ('image/jpeg', 'image/png', 'image/webp', 'video/mp4')
       OR size_bytes <= 0
       OR (mime_type IN ('image/jpeg', 'image/png', 'image/webp') AND size_bytes > 4194304)
       OR (mime_type = 'video/mp4' AND (size_bytes > 12582912 OR duration_seconds IS NULL OR duration_seconds > 30))
       OR (mime_type <> 'video/mp4' AND duration_seconds IS NOT NULL)
  ) THEN
    RAISE EXCEPTION 'TICKET_ATTACHMENT_BACKFILL_REQUIRED: existing media metadata is outside WF-08 limits';
  END IF;

  IF EXISTS (
    SELECT 1 FROM ticket_attachments
    WHERE (upload_status = 'DELETED') <> (deleted_at IS NOT NULL)
  ) THEN
    RAISE EXCEPTION 'TICKET_ATTACHMENT_STATE_BACKFILL_REQUIRED: deleted media timestamps are inconsistent';
  END IF;
END;
$$;

